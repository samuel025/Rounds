// Turns the two snarkjs verification keys into Rust constants in the byte format NEAR's alt_bn128 functions take
// (little-endian field elements; a G1 point is x||y = 64 bytes, a G2 point is x0||x1||y0||y1 = 128 bytes, in snarkjs's [c0, c1] order).
import { readFileSync, writeFileSync } from "node:fs";
const le = (dec) => { let n = BigInt(dec); const out = []; for (let i = 0; i < 32; i++) { out.push(Number(n & 0xffn)); n >>= 8n; } if (n !== 0n) throw new Error("field element too large"); return out; };
const g1 = (p) => [...le(p[0]), ...le(p[1])];
const g2 = (p) => [...le(p[0][0]), ...le(p[0][1]), ...le(p[1][0]), ...le(p[1][1])];
const arr = (bytes) => `[${bytes.join(", ")}]`;
for (const [name, mod] of [["cap_table_commit", "vk_cap_table"], ["private_claim", "vk_claim"]]) {
  const vk = JSON.parse(readFileSync(`contract/src/zk/${name}_verification_key.json`, "utf8"));
  const src = `// @generated by scripts/vk-to-rust.mjs from ${name}_verification_key.json. Do not edit.
// DEV / DEMO trusted setup (single contributor): see the README's Zero-Knowledge Confidential Mode section.
pub const NUM_PUBLIC: usize = ${vk.nPublic};
pub const ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};
pub const BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};
pub const GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};
pub const DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};
pub const IC: [[u8; 64]; ${vk.IC.length}] = [
${vk.IC.map((p) => "    " + arr(g1(p)) + ",").join("\n")}
];
`;
  writeFileSync(`contract/src/zk/${mod}.rs`, src); console.log(`wrote contract/src/zk/${mod}.rs (${vk.IC.length} IC points)`);
}
